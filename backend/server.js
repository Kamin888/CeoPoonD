async function purgeExpiredListings() {
  await pool.query("DELETE FROM listings WHERE deleted_at <= NOW() - INTERVAL '15 days'");
}

async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await pool.query(`
    ALTER TABLE users
    ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'user'
      CHECK (role IN ('user', 'admin'))
  `);
  await pool.query(
    "UPDATE users SET role = CASE WHEN email = ANY($1::text[]) THEN 'admin' ELSE 'user' END",
    [adminEmails]
  );

  await pool.query(`
    CREATE TABLE IF NOT EXISTS listings (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      slug TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL,
      area TEXT NOT NULL,
      price INTEGER NOT NULL CHECK (price >= 0),
      available BOOLEAN NOT NULL DEFAULT FALSE,
      transit BOOLEAN NOT NULL DEFAULT FALSE,
      pets BOOLEAN NOT NULL DEFAULT FALSE
    )
  `);

  await pool.query(`
    ALTER TABLE listings
    ADD COLUMN IF NOT EXISTS owner_id BIGINT REFERENCES users(id) ON DELETE SET NULL
  `);
  await pool.query(`
    ALTER TABLE listings
    ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'published'
      CHECK (status IN ('draft', 'pending_review', 'published', 'closed')),
    ADD COLUMN IF NOT EXISTS room_status TEXT NOT NULL DEFAULT 'vacant'
      CHECK (room_status IN ('vacant', 'occupied')),
    ADD COLUMN IF NOT EXISTS details JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS deleted_by BIGINT REFERENCES users(id) ON DELETE SET NULL
  `);
  await pool.query("UPDATE listings SET updated_at = created_at WHERE updated_at IS NULL");
  await pool.query(`
    ALTER TABLE listings
    ALTER COLUMN updated_at SET DEFAULT NOW(),
    ALTER COLUMN updated_at SET NOT NULL
  `);
  await purgeExpiredListings();
  await pool.query(
    `DELETE FROM listings
     WHERE slug = ANY($1::text[])`,
    [[
      "srisuk-residence",
      "baansuan-residence",
      "the-corner-apartment",
      "pimjai-mansion",
      "skyview-studio",
      "maneerat-place",
    ]]
  );
}

function validEmail(email) {
  return typeof email === "string" &&
    email.length <= 254 &&
    /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}

function setAuthCookie(response, user, status = 200) {
  const safeUser = { id: String(user.id), email: user.email, role: user.role };
  const token = jwt.sign({ email: safeUser.email }, jwtSecret, {
    subject: safeUser.id,
    expiresIn: "1h",
  });
  response.cookie("authToken", token, {
    httpOnly: true,
    secure: process.env.NODE_ENV === "production",
    sameSite: process.env.NODE_ENV === "production" ? "none" : "lax",
    maxAge: 60 * 60 * 1000,
    path: "/api",
  });
  response.status(status).json({ user: safeUser });
}

function parseBoolean(value, name) {
  if (value === undefined) return undefined;
  if (value === "true") return true;
  if (value === "false") return false;
  throw new Error(`${name} must be true or false.`);
}

function requireAuth(request, response, next) {
  const token = request.cookies.authToken;
  if (!token) return response.status(401).json({ error: "กรุณาเข้าสู่ระบบก่อนลงประกาศ" });

  try {
    const payload = jwt.verify(token, jwtSecret);
    if (typeof payload !== "object" || typeof payload.sub !== "string") {
      return response.status(401).json({ error: "เซสชันไม่ถูกต้อง กรุณาเข้าสู่ระบบใหม่" });
    }
    request.userId = payload.sub;
    next();
  } catch {
    response.status(401).json({ error: "เซสชันหมดอายุ กรุณาเข้าสู่ระบบใหม่" });
  }
}

function requireAdmin(request, response, next) {
  pool.query("SELECT role FROM users WHERE id = $1", [request.userId])
    .then(({ rows }) => {
      if (!rows[0]) return response.status(401).json({ error: "ไม่พบบัญชีผู้ใช้ กรุณาเข้าสู่ระบบใหม่" });
      if (rows[0].role !== "admin") return response.status(403).json({ error: "เฉพาะผู้ดูแลระบบเท่านั้นที่ดำเนินการนี้ได้" });
      next();
    })
    .catch(next);
}

function requireTrustedOrigin(request, response, next) {
  const origin = request.get("origin");
  if (origin && origin !== frontendOrigin) {
    return response.status(403).json({ error: "คำขอมาจากเว็บไซต์ที่ไม่ได้รับอนุญาต" });
  }
  next();
}

