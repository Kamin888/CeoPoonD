app.post("/api/auth/register", authRateLimit, async (request, response, next) => {
  try {
    const { email, password } = request.body ?? {};
    if (!validEmail(email)) {
      return response.status(400).json({ error: "กรุณากรอกอีเมลให้ถูกต้อง" });
    }
    if (typeof password !== "string" ||
        password.length < 8 ||
        Buffer.byteLength(password, "utf8") > 72) {
      return response.status(400).json({ error: "รหัสผ่านต้องมีอย่างน้อย 8 ตัวอักษร และไม่เกิน 72 ไบต์" });
    }

    const normalizedEmail = email.trim().toLowerCase();
    const passwordHash = await bcrypt.hash(password, 12);
    const { rows } = await pool.query(
      "INSERT INTO users (email, password_hash, role) VALUES ($1, $2, $3) RETURNING id, email, role",
      [normalizedEmail, passwordHash, adminEmails.includes(normalizedEmail) ? "admin" : "user"]
    );
    setAuthCookie(response, rows[0], 201);
  } catch (error) {
    if (error.code === "23505") {
      return response.status(409).json({ error: "อีเมลนี้ถูกใช้งานแล้ว" });
    }
    next(error);
  }
});

app.post("/api/auth/login", authRateLimit, async (request, response, next) => {
  try {
    const { email, password } = request.body ?? {};
    if (!validEmail(email) || typeof password !== "string" || password.length > 72) {
      return response.status(400).json({ error: "กรุณากรอกอีเมลและรหัสผ่านให้ถูกต้อง" });
    }

    const { rows } = await pool.query(
      "SELECT id, email, password_hash, role FROM users WHERE email = $1",
      [email.trim().toLowerCase()]
    );
    const user = rows[0];
    const passwordMatches = await bcrypt.compare(password, user?.password_hash ?? dummyPasswordHash);
    if (!user || !passwordMatches) {
      return response.status(401).json({ error: "อีเมลหรือรหัสผ่านไม่ถูกต้อง" });
    }

    setAuthCookie(response, user);
  } catch (error) {
    next(error);
  }
});

app.get("/api/auth/me", async (request, response, next) => {
  const token = request.cookies.authToken;
  if (!token) return response.status(401).json({ error: "กรุณาเข้าสู่ระบบ" });

  let payload;
  try {
    payload = jwt.verify(token, jwtSecret);
  } catch {
    response.clearCookie("authToken", {
      httpOnly: true,
      secure: process.env.NODE_ENV === "production",
      sameSite: process.env.NODE_ENV === "production" ? "none" : "lax",
      path: "/api",
    });
    return response.status(401).json({ error: "เซสชันหมดอายุ กรุณาเข้าสู่ระบบอีกครั้ง" });
  }
  if (typeof payload !== "object" || typeof payload.sub !== "string") {
    return response.status(401).json({ error: "เซสชันไม่ถูกต้อง กรุณาเข้าสู่ระบบใหม่" });
  }
  try {
    const { rows } = await pool.query("SELECT id, email, role FROM users WHERE id = $1", [payload.sub]);
    if (!rows[0]) return response.status(401).json({ error: "ไม่พบบัญชีผู้ใช้ กรุณาเข้าสู่ระบบใหม่" });
    response.json({ user: { id: String(rows[0].id), email: rows[0].email, role: rows[0].role } });
  } catch (error) {
    next(error);
  }
});

