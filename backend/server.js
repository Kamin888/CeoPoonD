app.patch("/api/listings/:id/status", requireTrustedOrigin, requireAuth, async (request, response, next) => {
  try {
    const { status } = request.body ?? {};
    if (!["closed", "pending_review"].includes(status)) {
      return response.status(400).json({ error: "สถานะที่ขอเปลี่ยนไม่ถูกต้อง" });
    }
    const { rows } = await pool.query(
      `UPDATE listings SET status = $1, updated_at = NOW()
       WHERE id = $2 AND owner_id = $3 AND deleted_at IS NULL
         AND ((status = 'published' AND $1 = 'closed') OR (status = 'closed' AND $1 = 'pending_review'))
       RETURNING id, status`,
      [status, request.params.id, request.userId]
    );
    if (!rows[0]) return response.status(404).json({ error: "ไม่พบประกาศหรือไม่สามารถเปลี่ยนสถานะนี้ได้" });
    response.json({ data: rows[0] });
  } catch (error) {
    next(error);
  }
});

app.get("/api/listings", async (request, response, next) => {
  try {
    const { search, maxPrice, transit, pets } = request.query;
    if (search !== undefined && (typeof search !== "string" || search.length > 100)) {
      return response.status(400).json({ error: "search must be a string of at most 100 characters." });
    }

    let parsedMaxPrice;
    if (maxPrice !== undefined) {
      if (typeof maxPrice !== "string" || !/^\d+$/.test(maxPrice)) {
        return response.status(400).json({ error: "maxPrice must be a non-negative integer." });
      }
      parsedMaxPrice = Number(maxPrice);
      if (!Number.isSafeInteger(parsedMaxPrice)) {
        return response.status(400).json({ error: "maxPrice must be a non-negative integer." });
      }
    }

    let parsedTransit;
    let parsedPets;
    try {
      parsedTransit = parseBoolean(transit, "transit");
      parsedPets = parseBoolean(pets, "pets");
    } catch (error) {
      return response.status(400).json({ error: error.message });
    }

    const conditions = ["listings.status = 'published'", "listings.deleted_at IS NULL"];
    const values = [];
    const addCondition = (sql, value) => {
      values.push(value);
      conditions.push(sql.replace("?", `$${values.length}`));
    };

    if (search?.trim()) {
      values.push(`%${search.trim()}%`);
      conditions.push(`name ILIKE $${values.length}`);
    }
    if (parsedMaxPrice !== undefined) addCondition("price <= ?", parsedMaxPrice);
    if (parsedTransit !== undefined) addCondition("transit = ?", parsedTransit);
    if (parsedPets !== undefined) addCondition("pets = ?", parsedPets);

    const where = conditions.length ? `WHERE ${conditions.join(" AND ")}` : "";
    const { rows } = await pool.query(
      `SELECT listings.id, listings.name, listings.area, listings.price, listings.available, listings.room_status,
              listings.transit, listings.pets, listings.details, listings.status,
              users.email AS owner_email
       FROM listings
       LEFT JOIN users ON users.id = listings.owner_id
       ${where}
       ORDER BY listings.id`,
      values
    );
    response.json({ data: rows });
  } catch (error) {
    next(error);
  }
});

app.use((error, _request, response, _next) => {
  console.error("API request failed:", error);
  if (error.status === 400 || error.status === 413) {
    const message = error.status === 413
      ? "ข้อมูลประกาศมีขนาดใหญ่เกินกำหนด"
      : "รูปแบบข้อมูลคำขอไม่ถูกต้อง";
    return response.status(error.status).json({ error: message });
  }
  response.status(500).json({ error: "Internal server error." });
});

let server;
let trashCleanupTimer;

async function start() {
  try {
    await initializeDatabase();
    server = app.listen(port);
    trashCleanupTimer = setInterval(() => {
      purgeExpiredListings().catch((error) => {
        console.error("Expired listing cleanup failed:", error);
      });
    }, 60 * 1000);
    console.log(`Backend listening on port ${port}`);
  } catch (error) {
    console.error("Database initialization failed:", error);
    process.exitCode = 1;
  }
}

async function shutdown() {
  if (trashCleanupTimer) clearInterval(trashCleanupTimer);
  if (server) server.close();
  await pool.end();
}

process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);

start();
