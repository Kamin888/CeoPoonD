export function translateText(language, value) {
  if (language !== "en" || typeof value !== "string") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const content = value.slice(leading.length, value.length - trailing.length || undefined);
  if (!content) return value;
  const patternTranslation = PATTERNS.reduce(
    (result, [pattern, replacement]) => result === content ? content.replace(pattern, replacement) : result,
    content
  );
  const translated = ENGLISH[content] || (patternTranslation !== content
    ? patternTranslation
    : content.includes(" · ")
    ? content.split(" · ").map((part) => translateText(language, part)).join(" · ")
    : content);
  return translated === content ? value : `${leading}${translated}${trailing}`;
}

const LOCALIZED_ATTRIBUTES = new Set(["alt", "aria-label", "placeholder", "title"]);

function localizeNode(node, language) {
  if (typeof node === "string") return translateText(language, node);
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, language));
  if (!React.isValidElement(node)) return node;

  const props = { ...node.props };
  for (const attribute of LOCALIZED_ATTRIBUTES) {
    if (typeof props[attribute] === "string") {
      props[attribute] = translateText(language, props[attribute]);
    }
  }
  return React.cloneElement(node, props, localizeNode(node.props.children, language));
}

export function Localized({ language, children }) {
  return localizeNode(children, language);
}
